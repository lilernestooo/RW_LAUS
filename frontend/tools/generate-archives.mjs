import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { pathToFileURL } from "node:url";

const POSTS_FILE = path.resolve("src/data/posts.js");
const OUT_FILE = path.resolve("archives.sql");

// Turn the image imports into plain strings so Node can load the module.
let src = fs.readFileSync(POSTS_FILE, "utf8");
src = src.replace(
  /import\s+(\w+)\s+from\s+["']\.\.\/assets\/images\/([^"']+)["'];?/g,
  (_m, name, file) => `const ${name} = ${JSON.stringify(file)};`
);

const tmp = path.join(os.tmpdir(), `rw-archives-${Date.now()}.mjs`);
fs.writeFileSync(tmp, src);
let mod;
try {
  mod = await import(pathToFileURL(tmp).href);
} finally {
  fs.unlinkSync(tmp);
}

const list = mod.archives;
if (!Array.isArray(list) || list.length === 0) {
  console.error("No `archives` array exported from src/data/posts.js");
  process.exit(1);
}

const months = ["january", "february", "march", "april", "may", "june", "july",
  "august", "september", "october", "november", "december"];

const rows = [];
for (const label of list) {
  const m = /^\s*([A-Za-z]+)\s+(\d{4})\s*$/.exec(String(label));
  const idx = m ? months.indexOf(m[1].toLowerCase()) : -1;
  if (idx === -1) {
    console.warn(`Skipped (not "Month YYYY"): ${label}`);
    continue;
  }
  const value = `${m[2]}-${String(idx + 1).padStart(2, "0")}`;
  const nice = `${m[1][0].toUpperCase()}${m[1].slice(1).toLowerCase()} ${m[2]}`;
  rows.push(`('${value}', '${nice}')`);
}

const sql = `-- Generated by tools/generate-archives.mjs
SET NAMES utf8mb4;
USE db_rw;

CREATE TABLE IF NOT EXISTS archives (
  value CHAR(7)     NOT NULL PRIMARY KEY,  -- e.g. 2026-09
  label VARCHAR(30) NOT NULL               -- e.g. September 2026
);

INSERT IGNORE INTO archives (value, label) VALUES
  ${rows.join(",\n  ")};
`;

fs.writeFileSync(OUT_FILE, sql, "utf8");
console.log(`Wrote ${OUT_FILE} (${rows.length} months)`);